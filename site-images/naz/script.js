/* =========================
   SAVE ORIGINAL KREYÒL
========================= */

const original = {};

document.querySelectorAll("[data-i18n]").forEach((element) => {
  original[element.dataset.i18n] = element.textContent;
});

/* =========================
   YEAR
========================= */

const yearElement = document.getElementById("year");

if (yearElement) {
  yearElement.textContent = new Date().getFullYear();
}

/* =========================
   LANGUAGE BUTTONS
========================= */

document.querySelectorAll(".lang").forEach((button) => {
  button.addEventListener("click", () => {
    const language = button.dataset.lang;

    document.documentElement.lang = language;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;

      if (language === "ht") {
        if (original[key] !== undefined) {
          element.textContent = original[key];
        }
      } else if (t[language] && t[language][key] !== undefined) {
        element.textContent = t[language][key];
      }
    });

    document.querySelectorAll(".lang").forEach((item) => {
      item.classList.toggle("active", item === button);
    });
  });
});

/* =========================
   DONATION AMOUNTS
========================= */

document.querySelectorAll(".amount").forEach((button) => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".amount").forEach((item) => {
      item.classList.remove("active");
    });

    button.classList.add("active");
  });
});

